"""Build the GenHacks fictional showcase from the real comparison worker."""

import argparse
import base64
import json
from pathlib import Path
from tempfile import TemporaryDirectory

from generate_demo import generate_pdf

from noticebridge.isolation import run_isolated_comparison

OUTPUT = Path(__file__).resolve().parents[2] / "frontend/src/showcase/generated.ts"
TITLE = "Riverton Student Grant"
COMMON = [
    "Eligibility: Class 12 or equivalent",
    "Required documents: photograph and identity card",
    "Application portal: example.invalid",
]


def build_showcase() -> str:
    with TemporaryDirectory(prefix="noticebridge-showcase-") as directory:
        root = Path(directory)
        paths = [root / "original-fictional-notice.pdf", root / "revised-fictional-notice.pdf"]
        for path, day, fee, interview in zip(
            paths, (19, 13), (500, 350), ("01/02/2027", "02/01/2027"), strict=True,
        ):
            generate_pdf(path, title=TITLE, lines=[
                f"Application deadline: {day} December 2026",
                f"Application fee: Rs. {fee}",
                f"Interview booking deadline: {interview}",
                *COMMON,
            ])
        pdfs = [path.read_bytes() for path in paths]
        report = run_isolated_comparison(
            *pdfs, old_name=paths[0].name, new_name=paths[1].name,
            enable_ocr=False, enable_semantic=False,
        )
        payload = {
            "format_version": 1,
            "sources": [
                {
                    "name": path.name, "role": role,
                    "base64": base64.b64encode(pdf).decode("ascii"),
                }
                for path, role, pdf in zip(paths, ("original", "revised"), pdfs, strict=True)
            ],
            "report": report.model_dump(mode="json"),
        }
        data = json.dumps(payload, ensure_ascii=False, indent=2)
        return (
            "// Generated by backend/benchmarks/generate_showcase.py.\n"
            "import type { DocumentRole, Report } from '../comparison';\n\n"
            f"export default {data} satisfies {{\n"
            "  format_version: 1;\n"
            "  sources: { name: string; role: DocumentRole; base64: string }[];\n"
            "  report: Report;\n"
            "};\n"
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the bundled fixture")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    bundle = build_showcase().encode("utf-8")
    if args.check:
        if not args.output.is_file() or args.output.read_bytes() != bundle:
            parser.error("Showcase fixture is stale. Regenerate it with generate_showcase.py.")
        print("Showcase report and source PDF bytes match the live comparison worker")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(bundle)
        print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
